    respond_to do |format|
      format.html
      format.pdf do 
        pdf = AllBranchesLicensesPdf.new(@license,@client,current_user,logo_path)
        send_data pdf.render, :filename => "#{@client.name.upcase} LICENSES.pdf"
      end
    end 

